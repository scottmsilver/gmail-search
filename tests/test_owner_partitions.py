def rows(conn, table):
    return conn.execute(sql.SQL('SELECT * FROM public.{} ORDER BY user_id,id').format(sql.Identifier(table))).fetchall()


def test_preview_is_read_only_and_attach_preserves_heaps_rows_indexes(source, migration):
    before = {table: rows(source, table) for table in ('messages','attachments','propositions')}
    identities = source.execute("SELECT relname,oid,relfilenode FROM pg_class WHERE oid IN ('messages'::regclass,'attachments'::regclass,'propositions'::regclass,'messages_bm25_idx'::regclass,'attachments_bm25_idx'::regclass,'props_bm25_idx'::regclass,'idx_props_msg'::regclass)").fetchall()
    preview = migration.preview_owner_partitions(source, owner_id='alice')
    assert preview['mode'] == 'attach_single_owner'
    assert len(preview['source_inventory']) == 3
    assert all(item['row_count']==1 and item['heap_bytes']>0 for item in preview['source_inventory'])
    assert source.execute("SELECT relkind FROM pg_class WHERE oid='messages'::regclass").fetchone() == ('r',)
    assert migration.migrate_owner_partitions(source, owner_id='alice') is True
    for table, original in before.items():
        assert rows(source, table) == original
        child = PARTITION_SCHEMA + '.' + partition_name(table, 'alice')
        old = next(item for item in identities if item[0] == table)
        assert source.execute('SELECT oid,relfilenode FROM pg_class WHERE oid=%s::regclass', (child,)).fetchone() == old[1:]
    for index in (item for item in identities if item[0].endswith('_idx') or item[0]=='idx_props_msg'):
        assert source.execute('SELECT relfilenode FROM pg_class WHERE oid=%s', (index[1],)).fetchone() == (index[2],)
    assert source.execute("SELECT id FROM messages WHERE user_id='alice' AND search_id @@@ 'subject:needle'").fetchall() == [('same',)]
    assert migration.migrate_owner_partitions(source, owner_id='alice') is False


def test_target_ids_are_owner_qualified_and_incoming_fks_reference_parents(source, migration):
    migration.migrate_owner_partitions(source, owner_id='alice')
    for table in ('messages','attachments','propositions'):
        source.execute(sql.SQL('CREATE TABLE {}.{} PARTITION OF public.{} FOR VALUES IN ({})').format(
            sql.Identifier(PARTITION_SCHEMA), sql.Identifier(partition_name(table,'bob')), sql.Identifier(table), sql.Literal('bob')))
    source.execute("INSERT INTO messages(id,user_id,search_id,thread_id,from_addr,to_addr) VALUES('same','bob',1,'thread','b','b')")
    source.execute("INSERT INTO attachments(id,user_id,message_id,filename,mime_type) VALUES(1,'bob','same','file','text/plain')")
    source.execute("INSERT INTO propositions(id,user_id,message_id,text,model) VALUES(1,'bob','same','bob fact','synthetic')")
    assert source.execute('SELECT count(*) FROM attachments WHERE id=1').fetchone() == (2,)
    source.execute("INSERT INTO embeddings(user_id,message_id,attachment_id) VALUES('bob','same',1)")
    with pytest.raises(psycopg.errors.UniqueViolation):
        source.execute("INSERT INTO attachments(id,user_id,message_id,filename,mime_type) VALUES(1,'bob','same','other','text/plain')")
    with pytest.raises(psycopg.errors.ForeignKeyViolation):
        source.execute("INSERT INTO propositions(user_id,message_id,text,model) VALUES('bob','missing','bad','synthetic')")
    new_id = source.execute("INSERT INTO messages(id,user_id,thread_id,from_addr,to_addr) VALUES('new','alice','thread','a','a') RETURNING search_id").fetchone()[0]
    assert new_id > 1


