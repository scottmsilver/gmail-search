def catalog_snapshot(conn):
    return {
        'relations': conn.execute("SELECT oid,relname,relnamespace,relowner,relfilenode,relacl,relrowsecurity,relforcerowsecurity FROM pg_class WHERE relnamespace='public'::regnamespace ORDER BY oid").fetchall(),
        'constraints': conn.execute("SELECT oid,conname,conrelid,confrelid,pg_get_constraintdef(oid) FROM pg_constraint WHERE connamespace='public'::regnamespace ORDER BY oid").fetchall(),
        'comments': conn.execute("SELECT * FROM pg_description WHERE objoid IN(SELECT oid FROM pg_class WHERE relnamespace='public'::regnamespace) ORDER BY objoid,objsubid").fetchall(),
        'defaults': conn.execute("SELECT d.adrelid,d.adnum,pg_get_expr(d.adbin,d.adrelid) FROM pg_attrdef d JOIN pg_class c ON c.oid=d.adrelid WHERE c.relnamespace='public'::regnamespace ORDER BY d.adrelid,d.adnum").fetchall(),
    }


def test_late_rollback_restores_catalog_and_dependent_rows(source, migration):
    source.execute("GRANT SELECT(id,user_id,subject) ON messages TO PUBLIC")
    before = catalog_snapshot(source)
    dependent_rows = {table: source.execute(sql.SQL('TABLE {}').format(sql.Identifier(table))).fetchall() for table in migration.DEPENDENTS}
    def fail(stage):
        if stage == 'attached':
            raise RuntimeError('late rollback')
    with pytest.raises(RuntimeError, match='late rollback'):
        migration.migrate_owner_partitions(source, owner_id='alice', _checkpoint=fail)
    assert catalog_snapshot(source) == before
    for table, values in dependent_rows.items():
        assert source.execute(sql.SQL('TABLE {}').format(sql.Identifier(table))).fetchall() == values


def test_column_grants_move_to_parent_and_private_leaves_deny_reader(source, migration):
    role = 'gms_owner_partitions_reader_' + secrets.token_hex(8)
    source.execute(sql.SQL('CREATE ROLE {} NOLOGIN').format(sql.Identifier(role)))
    try:
        source.execute(sql.SQL('GRANT USAGE ON SCHEMA public TO {}').format(sql.Identifier(role)))
        source.execute(sql.SQL('GRANT SELECT(id,user_id,subject) ON messages TO {}').format(sql.Identifier(role)))
        migration.migrate_owner_partitions(source, owner_id='alice')
        source.execute(sql.SQL('SET ROLE {}').format(sql.Identifier(role)))
        try:
            assert source.execute('SELECT id,user_id,subject FROM messages').fetchall() == [('same','alice','needle')]
            with pytest.raises(psycopg.errors.InsufficientPrivilege):
                source.execute('SELECT body_html FROM messages')
            with pytest.raises(psycopg.errors.InsufficientPrivilege):
                source.execute(sql.SQL('SELECT id FROM {}.{}').format(sql.Identifier(PARTITION_SCHEMA),sql.Identifier(partition_name('messages','alice'))))
        finally:
            source.execute('RESET ROLE')
    finally:
        source.execute(sql.SQL('DROP OWNED BY {}').format(sql.Identifier(role)))
        source.execute(sql.SQL('DROP ROLE {}').format(sql.Identifier(role)))


