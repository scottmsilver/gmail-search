@pytest.fixture
def derived(ingestion):
    conn, owners = ingestion
    conn.execute('ALTER TABLE propositions ALTER COLUMN id SET NOT NULL, ALTER COLUMN user_id SET NOT NULL, ALTER COLUMN message_id SET NOT NULL')
    conn.execute('ALTER TABLE propositions ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY')
    conn.execute('ALTER TABLE propositions ADD PRIMARY KEY(id), ADD COLUMN embedding bytea')
    conn.execute('CREATE TABLE prop_processed(user_id text, message_id text, PRIMARY KEY(user_id,message_id))')
    return conn, owners


def migration_module():
    path = Path(__file__).parents[1]/'deploy/public/migrate_derived_owner_keys.py'
    spec = importlib.util.spec_from_file_location('derived_owner_keys', path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_foreign_parent_is_refused_before_embedding(derived):
    conn, (alice, bob) = derived
    queries.upsert_message(conn, message(alice), user_id=alice)
    embedder = Mock(model='synthetic')
    embedder.embed_texts_batch.return_value = [[1., 2.]]
    with pytest.raises(ValueError, match='owner'):
        propositions.store_propositions(conn, embedder, user_id=bob, message_id='collision', thread_id='thread', date=None, facts=['fact'])
    embedder.embed_texts_batch.assert_not_called()
    assert conn.execute('SELECT count(*) AS n FROM propositions').fetchone()['n'] == 0


def test_derived_migration_cascades_only_deleted_owner_and_is_idempotent(derived):
    conn, (alice, bob) = derived
    migration = migration_module()
    for owner in (alice, bob):
        queries.upsert_message(conn, message(owner), user_id=owner)
        conn.execute("INSERT INTO propositions(user_id,message_id,text,model) VALUES(%s,'collision',%s,'synthetic')", (owner, owner))
        conn.execute("INSERT INTO prop_processed VALUES(%s,'collision')", (owner,))
    assert migration.migrate_derived_owner_keys(conn)
    assert not migration.migrate_derived_owner_keys(conn)
    for table in ('propositions', 'prop_processed'):
        with pytest.raises(psycopg.errors.ForeignKeyViolation):
            if table == 'propositions':
                conn.execute("INSERT INTO propositions(user_id,message_id,text,model) VALUES(%s,'missing','foreign','synthetic')", (alice,))
            else:
                conn.execute("INSERT INTO prop_processed VALUES(%s,'missing')", (alice,))
    conn.execute("DELETE FROM messages WHERE user_id=%s AND id='collision'", (alice,))
    assert conn.execute('SELECT user_id,text FROM propositions').fetchall() == [{'user_id': bob, 'text': bob}]
    assert conn.execute('SELECT user_id FROM prop_processed').fetchall() == [{'user_id': bob}]


def test_orphan_refuses_migration_without_partial_constraints(derived):
    conn, (alice, _) = derived
    conn.execute("INSERT INTO propositions(user_id,message_id,text,model) VALUES(%s,'missing','fact','synthetic')", (alice,))
    with pytest.raises(ValueError, match='orphan'):
        migration_module().migrate_derived_owner_keys(conn)
    assert conn.execute("SELECT count(*) AS n FROM pg_constraint WHERE conrelid='propositions'::regclass AND contype='f'").fetchone()['n'] == 0


def test_pending_derived_markers_and_facts_stay_owner_scoped(derived, monkeypatch):
    conn, (alice, bob) = derived
    migration_module().migrate_derived_owner_keys(conn)
    for owner in (alice, bob):
        queries.upsert_message(conn, message(owner), user_id=owner)
    monkeypatch.setattr(propositions, 'extract_propositions', lambda *args, **kwargs: ['fact'])
    embedder = Mock(model='synthetic')
    embedder.embed_texts_batch.return_value = [[1., 2.]]
    assert propositions.propositionize_pending(conn, None, None, embedder, user_id=alice, owner='Alice')['facts'] == 1
    assert conn.execute('SELECT user_id FROM propositions').fetchall() == [{'user_id': alice}]
    assert conn.execute('SELECT user_id FROM prop_processed').fetchall() == [{'user_id': alice}]


