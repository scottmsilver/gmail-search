def test_main_migration_reapplies_after_derived_keys(legacy_schema, main_migration):
    conn = legacy_schema
    main_migration.migrate_owner_keys(conn)
    conn.execute('CREATE TABLE propositions(id bigserial PRIMARY KEY,user_id text NOT NULL,message_id text NOT NULL)')
    conn.execute('CREATE TABLE prop_processed(user_id text,message_id text,PRIMARY KEY(user_id,message_id))')
    assert migration_module().migrate_derived_owner_keys(conn)
    assert not main_migration.migrate_owner_keys(conn)


def test_parent_deleted_during_embedding_does_not_create_legacy_orphan(derived):
    conn, (alice, _) = derived
    queries.upsert_message(conn, message(alice), user_id=alice)
    embedder = Mock(model='synthetic')
    def deleting(facts):
        conn.execute('DELETE FROM messages WHERE user_id=%s', (alice,))
        return [[1., 2.]]
    embedder.embed_texts_batch.side_effect = deleting
    with pytest.raises(ValueError, match='owner'):
        propositions.store_propositions(conn, embedder, user_id=alice, message_id='collision', thread_id='thread', date=None, facts=['fact'])
    assert conn.execute('SELECT count(*) AS n FROM propositions').fetchone()['n'] == 0


def test_target_schema_refuses_nullable_owner_regression(derived):
    conn, _ = derived
    migration_module().migrate_derived_owner_keys(conn)
    conn.execute('ALTER TABLE propositions ALTER COLUMN user_id DROP NOT NULL')
    with pytest.raises(ValueError, match='nullability'):
        migration_module().migrate_derived_owner_keys(conn)


def test_migration_preserves_existing_policies_and_grants(derived):
    conn, _ = derived
    def snapshot():
        return conn.execute("SELECT relacl,relrowsecurity,relforcerowsecurity FROM pg_class WHERE oid='propositions'::regclass").fetchone(), conn.execute("SELECT polname,pg_get_expr(polqual,polrelid) AS expression FROM pg_policy WHERE polrelid='propositions'::regclass").fetchall()
    before = snapshot()
    migration_module().migrate_derived_owner_keys(conn)
    assert snapshot() == before


def test_null_owner_and_unexpected_unique_index_are_refused(derived):
    conn, _ = derived
    conn.execute('ALTER TABLE propositions ALTER COLUMN user_id DROP NOT NULL')
    conn.execute("INSERT INTO propositions(user_id,message_id,text,model) VALUES(NULL,'missing','fact','synthetic')")
    with pytest.raises(ValueError, match='null'):
        migration_module().migrate_derived_owner_keys(conn)
    conn.execute('DELETE FROM propositions')
    conn.execute('CREATE UNIQUE INDEX unsupported_derived_identity ON propositions(message_id)')
    with pytest.raises(ValueError, match='unique index'):
        migration_module().migrate_derived_owner_keys(conn)
