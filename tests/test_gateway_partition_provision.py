@pytest.fixture
def partition_database(request):
    dsn = os.getenv('GMS_TEST_PG_DSN')
    if not dsn:
        pytest.skip('GMS_TEST_PG_DSN synthetic ParadeDB fixture required')
    cfg = conninfo_to_dict(dsn)
    assert (cfg.get('host'), cfg.get('port'), cfg.get('dbname'), cfg.get('user')) == ('127.0.0.1', '55440', 'postgres', 'postgres')
    assert not set(cfg) & {'hostaddr', 'service', 'options'}
    name = 'gms_partition_provision_' + secrets.token_hex(8)
    target = make_conninfo(dsn, dbname=name)
    with psycopg.connect(dsn, autocommit=True) as admin:
        admin.execute(sql.SQL('CREATE DATABASE {} TEMPLATE template0').format(sql.Identifier(name)))
    try:
        with psycopg.connect(target, autocommit=True) as conn:
            conn.execute('CREATE EXTENSION pg_search')
            variant = getattr(request,'param',None)
            nocase = variant == 'nocase'
            if variant in ('nocase','users_nocase'):
                conn.execute("CREATE COLLATION public.owner_nocase(provider=icu,locale='und-u-ks-level2',deterministic=false)")
            def ddl(statement):
                if nocase:statement=statement.replace('user_id text NOT NULL','user_id text COLLATE public.owner_nocase NOT NULL')
                conn.execute(statement)
            assert conn.execute("SELECT extversion FROM pg_extension WHERE extname='pg_search'").fetchone() == ('0.23.0',)
            # 16.15 since 2026-09-16: the patched pg_search image is built on
            # ParadeDB's current Dockerfile, which pulls postgres:16-trixie.
            assert conn.info.server_version == 160015
            conn.execute("CREATE TABLE public.users(id text" + (" COLLATE public.owner_nocase" if variant == "users_nocase" else "") + " PRIMARY KEY)")
            conn.execute("INSERT INTO public.users VALUES ('alice'),('bob')")
            ddl('''CREATE TABLE public.messages(user_id text NOT NULL REFERENCES public.users ON DELETE CASCADE,
                id text NOT NULL,search_id bigint GENERATED BY DEFAULT AS IDENTITY,subject text,body_text text,from_addr text,to_addr text,
                PRIMARY KEY(user_id,id),UNIQUE(user_id,search_id)) PARTITION BY LIST(user_id)''')
            ddl('''CREATE TABLE public.attachments(user_id text NOT NULL REFERENCES public.users ON DELETE CASCADE,
                id bigint NOT NULL,message_id text NOT NULL,filename text NOT NULL,extracted_text text,
                PRIMARY KEY(user_id,id),UNIQUE(user_id,message_id,filename),UNIQUE(user_id,message_id,id),
                FOREIGN KEY(user_id,message_id) REFERENCES public.messages(user_id,id)) PARTITION BY LIST(user_id)''')
            ddl('''CREATE TABLE public.propositions(user_id text NOT NULL,id bigint NOT NULL,message_id text NOT NULL,text text,
                PRIMARY KEY(user_id,id),FOREIGN KEY(user_id,message_id) REFERENCES public.messages(user_id,id) ON DELETE CASCADE) PARTITION BY LIST(user_id)''')
            for table in ('messages','attachments','propositions'):
                conn.execute(sql.SQL('ALTER TABLE public.{} ENABLE ROW LEVEL SECURITY').format(sql.Identifier(table)))
                conn.execute(sql.SQL('ALTER TABLE public.{} FORCE ROW LEVEL SECURITY').format(sql.Identifier(table)))
            conn.execute("CREATE INDEX messages_bm25_idx ON public.messages USING bm25(search_id,id,subject,body_text,from_addr,to_addr) WITH(key_field='search_id')")
            conn.execute("CREATE INDEX attachments_bm25_idx ON public.attachments USING bm25(id,filename,extracted_text) WITH(key_field='id')")
            conn.execute("CREATE INDEX props_bm25_idx ON public.propositions USING bm25(id,text) WITH(key_field='id')")
        yield target
    finally:
        with psycopg.connect(dsn, autocommit=True) as admin:
            admin.execute(sql.SQL('DROP DATABASE {} WITH (FORCE)').format(sql.Identifier(name)))


def test_provisions_idempotently_with_real_native_parent_search(partition_database):
    with psycopg.connect(partition_database, autocommit=True) as conn:
        partitions.provision_owner_partitions(conn, 'alice')
        partitions.provision_owner_partitions(conn, 'bob')
        before = conn.execute("SELECT oid FROM pg_class WHERE relnamespace='gms_mail_partitions'::regnamespace ORDER BY oid").fetchall()
        partitions.provision_owner_partitions(conn, 'alice')
        assert partitions.verify_owner_partitions(conn, 'alice') is None
        assert conn.execute("SELECT oid FROM pg_class WHERE relnamespace='gms_mail_partitions'::regnamespace ORDER BY oid").fetchall() == before
        conn.execute("INSERT INTO public.messages(user_id,id,body_text) VALUES ('alice','same','needle'),('bob','same','foreign')")
        assert conn.execute("SELECT id FROM public.messages WHERE user_id='alice' AND search_id @@@ 'body_text:needle'").fetchall() == [('same',)]


