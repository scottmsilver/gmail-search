def test_remove_empty_owner_then_delete_user_preserves_other_owners(partition_database):
    with psycopg.connect(partition_database,autocommit=True) as conn:
        partitions.provision_owner_partitions(conn,'alice')
        partitions.provision_owner_partitions(conn,'bob')
        conn.execute("INSERT INTO public.messages(user_id,id,body_text) VALUES ('alice','kept','private')")
        alice = conn.execute('SELECT to_regclass(%s)::oid',('gms_mail_partitions.'+partitions.partition_name('messages','alice'),)).fetchone()[0]
        with conn.transaction():
            partitions.remove_empty_owner_partitions(conn,'bob')
            partitions.remove_empty_owner_partitions(conn,'bob')
            conn.execute("DELETE FROM public.users WHERE id='bob'")
        partitions.verify_owner_partitions(conn,'alice')
        assert conn.execute('SELECT to_regclass(%s)::oid',('gms_mail_partitions.'+partitions.partition_name('messages','alice'),)).fetchone()[0] == alice
        assert conn.execute('SELECT user_id,id FROM public.messages').fetchall()==[('alice','kept')]
        conn.execute("INSERT INTO public.users VALUES ('charlie')")
        partitions.provision_owner_partitions(conn,'charlie')
        partitions.verify_owner_partitions(conn,'charlie')


