def test_lock_budget_and_caller_settings_survive_contention(partition_database):
    import time
    with psycopg.connect(partition_database,autocommit=True) as blocker, psycopg.connect(partition_database,autocommit=True) as conn:
        conn.execute("SET lock_timeout='7s'")
        conn.execute("SET statement_timeout='5s'")
        with blocker.transaction():
            blocker.execute('SELECT pg_advisory_xact_lock(hashtextextended(%s,0))',('gmail-search partition owner alice',))
            start=time.monotonic()
            with pytest.raises(psycopg.errors.LockNotAvailable):
                partitions.provision_owner_partitions(conn,'alice')
            assert time.monotonic()-start<4
        assert conn.execute("SELECT current_setting('lock_timeout'),current_setting('statement_timeout')").fetchone()==('7s','5s')
        partitions.provision_owner_partitions(conn,'alice')
        assert conn.execute("SELECT current_setting('lock_timeout'),current_setting('statement_timeout')").fetchone()==('7s','5s')


