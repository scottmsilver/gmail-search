def test_caller_rollback_and_competing_provisioners(partition_database):
    with psycopg.connect(partition_database, autocommit=True) as conn:
        with pytest.raises(RuntimeError):
            with conn.transaction():
                partitions.provision_owner_partitions(conn, 'alice')
                raise RuntimeError('injected rollback')
        assert conn.execute("SELECT to_regnamespace('gms_mail_partitions')").fetchone() == (None,)
    def provision(_):
        with psycopg.connect(partition_database, autocommit=True) as conn:
            partitions.provision_owner_partitions(conn, 'alice')
    with ThreadPoolExecutor(max_workers=2) as pool:
        list(pool.map(provision, range(2)))
    with psycopg.connect(partition_database, autocommit=True) as conn:
        partitions.verify_owner_partitions(conn, 'alice')


