@pytest.mark.parametrize('object_kind',['schema','sequence','default','owner'])
def test_private_acl_sources_fail_closed(partition_database, runtime_identity, object_kind):
    role, _ = runtime_identity
    with psycopg.connect(partition_database, autocommit=True) as conn:
        partitions.provision_owner_partitions(conn,'alice')
        if object_kind=='schema':
            conn.execute(sql.SQL('GRANT USAGE ON SCHEMA gms_mail_partitions TO {}').format(sql.Identifier(role)))
        elif object_kind=='sequence':
            conn.execute('CREATE SEQUENCE gms_mail_partitions.unexpected_sequence')
            conn.execute(sql.SQL('GRANT USAGE ON SEQUENCE gms_mail_partitions.unexpected_sequence TO {}').format(sql.Identifier(role)))
        elif object_kind=='default':
            conn.execute(sql.SQL('ALTER DEFAULT PRIVILEGES IN SCHEMA gms_mail_partitions GRANT SELECT ON TABLES TO {}').format(sql.Identifier(role)))
        else:
            conn.execute(sql.SQL('ALTER SCHEMA gms_mail_partitions OWNER TO {}').format(sql.Identifier(role)))
            conn.execute(sql.SQL('REVOKE ALL ON SCHEMA gms_mail_partitions FROM {}').format(sql.Identifier(role)))
        try:
            with pytest.raises(ValueError):
                partitions.provision_owner_partitions(conn,'bob')
        finally:
            if object_kind=='owner':
                conn.execute('ALTER SCHEMA gms_mail_partitions OWNER TO postgres')
        assert conn.execute('SELECT to_regclass(%s)', ('gms_mail_partitions.'+partitions.partition_name('messages','bob'),)).fetchone() == (None,)


