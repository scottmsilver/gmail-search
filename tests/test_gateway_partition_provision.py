def test_remove_unknown_dependent_object_rolls_back_earlier_detaches(partition_database):
    with psycopg.connect(partition_database,autocommit=True) as conn:
        partitions.provision_owner_partitions(conn,'bob')
        child=sql.Identifier(partitions.PARTITION_SCHEMA,partitions.partition_name('messages','bob'))
        conn.execute(sql.SQL('CREATE VIEW public.hold_owner_leaf AS SELECT id FROM {}').format(child))
        with pytest.raises(psycopg.errors.DependentObjectsStillExist):
            partitions.remove_empty_owner_partitions(conn,'bob')
        partitions.verify_owner_partitions(conn,'bob')
        assert conn.execute("SELECT to_regclass('public.hold_owner_leaf')").fetchone()[0]
        for table in ('messages','attachments','propositions'):
            assert conn.execute('SELECT to_regclass(%s)',(partitions.PARTITION_SCHEMA+'.'+partitions.partition_name(table,'bob'),)).fetchone()[0]
