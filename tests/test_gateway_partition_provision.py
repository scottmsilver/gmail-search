@pytest.mark.parametrize('fault', ['bound','default','metadata','rls','column_grant','schema_grant','index','parent_index','parent_key','foreign_key','parent_rls','ancestry'])
def test_catalog_drift_rejected_without_repair(partition_database, fault):
    with psycopg.connect(partition_database, autocommit=True) as conn:
        partitions.provision_owner_partitions(conn, 'alice')
        child = sql.Identifier(partitions.PARTITION_SCHEMA, partitions.partition_name('messages','alice'))
        if fault in ('bound','default','ancestry'):
            conn.execute(sql.SQL('ALTER TABLE public.messages DETACH PARTITION {}').format(child))
            if fault == 'bound':
                conn.execute(sql.SQL("ALTER TABLE public.messages ATTACH PARTITION {} FOR VALUES IN ('bob')").format(child))
            elif fault == 'default':
                conn.execute(sql.SQL('ALTER TABLE public.messages ATTACH PARTITION {} DEFAULT').format(child))
        elif fault == 'metadata':
            conn.execute(sql.SQL("COMMENT ON TABLE {} IS 'forged'").format(child))
        elif fault == 'rls':
            conn.execute(sql.SQL('ALTER TABLE {} NO FORCE ROW LEVEL SECURITY').format(child))
        elif fault == 'column_grant':
            conn.execute(sql.SQL('GRANT SELECT(subject) ON {} TO PUBLIC').format(child))
        elif fault == 'schema_grant':
            conn.execute('GRANT USAGE ON SCHEMA gms_mail_partitions TO PUBLIC')
        elif fault == 'index':
            conn.execute(sql.SQL('ALTER TABLE public.messages DETACH PARTITION {}').format(child))
            index = conn.execute("SELECT c.relname FROM pg_index i JOIN pg_class c ON c.oid=i.indexrelid JOIN pg_am a ON a.oid=c.relam WHERE i.indrelid=%s::regclass AND a.amname='bm25'", (child.as_string(conn),)).fetchone()[0]
            conn.execute(sql.SQL('DROP INDEX {}').format(sql.Identifier(partitions.PARTITION_SCHEMA,index)))
        elif fault == 'parent_index':
            conn.execute('DROP INDEX public.messages_bm25_idx')
        elif fault == 'parent_key':
            conn.execute('ALTER TABLE public.messages DROP CONSTRAINT messages_user_id_search_id_key')
        elif fault == 'foreign_key':
            conn.execute('ALTER TABLE public.propositions DROP CONSTRAINT propositions_user_id_message_id_fkey')
        elif fault == 'parent_rls':
            conn.execute('ALTER TABLE public.messages NO FORCE ROW LEVEL SECURITY')
        for operation in (partitions.verify_owner_partitions, partitions.provision_owner_partitions):
            with pytest.raises(ValueError):
                operation(conn, 'alice')


